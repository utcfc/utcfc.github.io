#!/usr/bin/env python3
"""Package Pop III SFRD CSV bytes from the files in in data/popiii-sfrd/ for the offline-capable viewer.
This script should be run manually after updating the CSV files in data/popiii-sfrd/ and before committing changes to the repository.
"""
import base64
import json
from pathlib import Path


ASSET_DIR = Path(__file__).resolve().parent  # Directory containing this script
ROOT = ASSET_DIR.parent.parent  # Repository root
CSV_DIR = ROOT / "data" / "popiii-sfrd"  # Directory containing original CSV files
OUTPUT = ASSET_DIR / "models_data.js"  # Generated JavaScript

files = sorted(CSV_DIR.glob("*.csv"))
if not files:
    raise SystemExit("No CSV files found in " + str(CSV_DIR))
encoded = {
    f.name: base64.b64encode(f.read_bytes()).decode("ascii")
    for f in files
}
OUTPUT.write_text(
    "/* Generated from data/popiii-sfrd/*.csv; do not edit this file manually. */\n"
    "window.POPIII_SFRD_CSV_BASE64 = Object.freeze(\n"
    + json.dumps(encoded, indent=2, ensure_ascii=True)
    + "\n);\n",
    encoding="utf-8",
)
print(f"Embedded {len(files)} original CSV files in {OUTPUT}")
